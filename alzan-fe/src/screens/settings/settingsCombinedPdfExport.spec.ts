import assert from 'node:assert/strict';
import { createCombinedPdfHtml, extractPdfHtmlSection } from './settingsCombinedPdfHtml';

const first = `
  <html>
    <head><style>.first { color: red; }</style></head>
    <body>
      <div class="cover">First cover</div>
      <div class="footer">First footer</div>
      <main class="first">First body</main>
    </body>
  </html>
`;

const second = `
  <html>
    <head><style>.second { color: blue; }</style></head>
    <body>
      <div class="cover">Second cover</div>
      <div class="footer">
        Second footer
      </div>
      <main class="second">Second body</main>
    </body>
  </html>
`;

const firstSection = extractPdfHtmlSection(first);
assert.equal(firstSection.styles.trim(), '.first { color: red; }');
assert.match(firstSection.body, /First cover/);
assert.match(firstSection.body, /First body/);
assert.doesNotMatch(firstSection.body, /First footer/);

const combined = createCombinedPdfHtml({
  sections: [
    { label: 'Health', html: first },
    { label: 'Workout', html: second },
  ],
  footer: 'Generated by Alzan',
});

assert.match(combined, /First body/);
assert.match(combined, /Second body/);
assert.match(combined, /\.first \{ color: red; \}/);
assert.match(combined, /\.second \{ color: blue; \}/);
assert.match(combined, /Generated by Alzan/);
assert.equal((combined.match(/<section class="combined-report-section"/g) ?? []).length, 2);
assert.equal((combined.match(/class="footer"/g) ?? []).length, 1);
